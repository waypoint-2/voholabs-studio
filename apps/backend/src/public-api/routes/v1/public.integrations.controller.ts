  // Read-only history of an Instagram channel's existing media. Tenant scoped:
  // an id from another organization is a plain 404 and nothing is requested
  // from Instagram. Failures use fixed { code, message } bodies.
  @Get('/integrations/:id/media')
  async listIntegrationMedia(
    @GetOrgFromRequest() org: Organization,
    @Param('id') id: string,
    @Query('limit') limit?: string | string[],
    @Query('cursor') cursor?: string | string[]
  ) {
    Sentry.metrics.count('public_api-request', 1);
    try {
      const result = await this._integrationService.listRecentMedia(org.id, id, {
        limit: parseLimit(limit),
        after: decodeCursor(cursor),
      });
      return {
        integration_id: result.integrationId,
        provider: result.provider,
        fetched_at: new Date().toISOString(),
        media: result.media,
        paging: { next_cursor: result.nextCursor },
      };
    } catch (error) {
      if (!(error instanceof RecentMediaError)) {
        // Name only: the error can carry request URLs, and so tokens.
        console.error(
          'Recent media failed:',
          error instanceof Error ? error.name : typeof error
        );
      }
      const { status, body } = toRecentMediaErrorResponse(error);
      throw new HttpException(body, status);
    }
  }

  @Get('/social/:integration')
  @CheckPolicies([AuthorizationActions.Create, Sections.CHANNEL])
  async getIntegrationUrl(
    @Param('integration') integration: string,
    @Query('refresh') refresh: string,
    @GetOrgFromRequest() org: Organization
  ) {
    Sentry.metrics.count('public_api-request', 1);
    if (
      !this._integrationManager
        .getAllowedSocialsIntegrations()
        .includes(integration)
    ) {
      throw new HttpException({ msg: 'Integration not allowed' }, 400);
    }

    if (!(await this._integrationService.canUseProvider(org.id, integration))) {
      const locked = await this._walletService.providerLocked(
        org.id,
        integration,
        paidOnlyChannelMessage()
      );
      const body = locked.getResponse();
      // `msg` is what this API has always returned; the wallet fields ride
      // along when a top-up opens the channel.
      throw new HttpException(
        typeof body === 'string'
          ? { msg: body }
          : { msg: locked.message, ...(body as object) },
        402
      );
    }

    const integrationProvider =
      this._integrationManager.getSocialIntegration(integration);

    if (integrationProvider.externalUrl) {
      throw new HttpException(
        {
          msg: 'This integration requires an external URL and is not supported via the public API',
        },
        400
      );
    }

    try {
      const { codeVerifier, state, url } =
        await integrationProvider.generateAuthUrl();

      if (refresh) {
        await ioRedis.set(`refresh:${state}`, refresh, 'EX', 3600);
      }

      await ioRedis.set(`organization:${state}`, org.id, 'EX', 3600);
      await ioRedis.set(`login:${state}`, codeVerifier, 'EX', 3600);

      return { url };
    } catch (err) {
      throw new HttpException({ msg: 'Failed to generate auth URL' }, 500);
    }
  }

